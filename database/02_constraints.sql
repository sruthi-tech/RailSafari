ALTER TABLE PASSENGER ADD CONSTRAINT CHK_PASSENGER_AGE CHECK (AGE > 0 AND AGE <= 120);
ALTER TABLE PASSENGER ADD CONSTRAINT CHK_PASSENGER_GENDER CHECK (GENDER IN ('MALE', 'FEMALE', 'OTHER'));

-- PAYMENT Constraints

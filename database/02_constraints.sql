-- COACH Constraints
ALTER TABLE COACH ADD CONSTRAINT FK_COACH_TRAIN FOREIGN KEY (TRAIN_ID) REFERENCES TRAIN(TRAIN_ID);

-- SEAT Constraints
ALTER TABLE SEAT ADD CONSTRAINT FK_SEAT_COACH FOREIGN KEY (COACH_ID) REFERENCES COACH(COACH_ID);
ALTER TABLE SEAT ADD CONSTRAINT CHK_SEAT_STATUS CHECK (SEAT_STATUS IN ('AVAILABLE', 'BOOKED', 'RESERVED'));

-- BOOKING Constraints
